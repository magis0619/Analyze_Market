import { COLORS } from '../render/palette';

// UI デザイントークン（Balatro型UI設計書 Phase 1）。
//
// 画面ごとに数値を直接書かない。余白・枠・影・文字サイズ・色の役割・重なり順・
// 演出の長さを、すべてここの語彙で表す。調査時点で「生の矩形描画170回 対
// 共通部品56回」という状態で、同じ意味のパネルが画面ごとに違う余白と枠幅で
// 描かれていた。まずここを一本化する。

// ---------------------------------------------------------------- 余白（§13）
//
// 「何もない場所を恐れない」。余白は情報のグループを分ける唯一の手段なので、
// 段階を決めて、その中間値は使わない。
export const SPACE = {
  /** 密着させたくないだけ（アイコンと文字の間など） */
  xs: 2,
  /** 同じカードの中の行間 */
  sm: 4,
  /** 標準。パネルの内側の余白 */
  md: 8,
  /** 異なるグループの間 */
  lg: 12,
  /** 章が変わる区切り */
  xl: 20
} as const;

// ---------------------------------------------------------------- 枠（§14）
//
// 1px / 2px / 4px の3種だけ。角丸は使わない（ドットが崩れるため）。
export const BORDER = {
  /** 区切り線・控えめな枠 */
  thin: 1,
  /** 選択中・注目させる枠 */
  base: 2,
  /** 最上位のレアリティなど、格を示す枠 */
  thick: 4
} as const;

/** ハードシャドウの落とし幅（§14）。ぼかしは使わない。 */
export const SHADOW = 2;

// ---------------------------------------------------------------- 文字（§4）
//
// 設計書 §4 は「すべての文字を同じ大きさにしない」と求めるが、
// 仕様書 §9.3 は「1画面に3種類以上のフォントサイズ」を禁止している。
// 両立させるため、**サイズは2段のまま**にして、優先順位はサイズだけでなく
//   サイズ（2段） → 色（text / dim / faint） → 位置（上ほど重要） → アクセント帯
// の4つを重ねて表す。数値そのものは TEXT.title を使い、説明文は TEXT.body に落とす。
export const TEXT = {
  /** 本文・数値の単位・説明。12pxセル */
  body: 8,
  /** 見出し・主要数値。16pxセル */
  title: 12
} as const;

// ---------------------------------------------------------------- 重なり順（§6）
//
// 「すべての情報を平面的に表示しない」。描画順をここで宣言し、
// 各画面はこの順に描く。数字が大きいほど手前。
export const Z = {
  background: 0,
  panel: 1,
  card: 2,
  /** 選択中のカードは一段持ち上げる */
  selected: 3,
  /** 背後を覆う暗幕 */
  overlay: 4,
  /** 詳細ポップアップ・モーダル */
  popup: 5,
  /** 通知・飛ぶ数字 */
  toast: 6
} as const;

// ---------------------------------------------------------------- 演出（§15）
//
// アニメーションは「装飾」ではなく「状態変化の説明」。
// 長いトランジションと常時点滅は作らない。単位は秒。
export const DUR = {
  /** 押した瞬間の沈み込み */
  tap: 0.08,
  /** カードが跳ねる・数字が拡大して戻る */
  pop: 0.28,
  /** 増減値が浮き上がって消えるまで */
  float: 0.9,
  /** 通知が出てから消えるまで */
  toast: 2.4
} as const;

// ---------------------------------------------------------------- 色の役割（§5）
