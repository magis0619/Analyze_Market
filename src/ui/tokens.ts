// ---------------------------------------------------------------- 操作の状態（§7 §12）
//
// 設計書 §7 は hover → focus → selected の遷移を求めるが、
// この作品はタッチ専用（内部解像度360×640・縦持ち）なので hover が存在しない。
// 代わりに「押している間」を明示し、通常／選択中／押下中／無効の4状態にする。
// 触れるものにはこの4状態を必ず用意し、ただのテキストには何も付けない。
export type UiState = 'normal' | 'selected' | 'pressed' | 'disabled';
